    private void btnAGREGARActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAGREGARActionPerformed
         try {
            Marca marca = new Marca();
            marca.setNombreMarca(txtNombre.getText().trim());
            marca.setDescripcion(txtDescripcion.getText().trim());
            marca.setPaisOrigen(txtPaisOrigen.getText().trim());
            marca.setEstado(true);

            marControl.agregarMarca(marca);   // BD + nodo al final de la lista

            Mensajes.exito("La marca ha sido agregada exitosamente!");
            limpiarCampos();

            // Si era la primera marca, se muestra en el panel de la derecha
            if (nodoActual == null) {
                mostrarNodo(marControl.getCabeza());
            }
        } catch (Exception e) {
            Mensajes.error(e.getMessage());
        }
    }//GEN-LAST:event_btnAGREGARActionPerformed

    private void btnACTUALIZARActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnACTUALIZARActionPerformed
           try {
            int id = Validaciones.parsearId(txtID.getText());

            boolean segundoClic = marcaActualizar != null && marcaActualizar.getIdMarca() == id;

            if (!segundoClic) {
                // 1er clic: buscar por ID y completar los campos
                NodoEnlazadaSimple nodo = marControl.buscarNodoPorId(id);
                if (nodo == null) {
                    marcaActualizar = null;
                    Mensajes.error("No existe una marca con el ID " + id + ".");
                    return;
                }
                marcaActualizar = nodo.getDato();
                txtNombre.setText(marcaActualizar.getNombreMarca());
                txtDescripcion.setText(marcaActualizar.getDescripcion());
                txtPaisOrigen.setText(marcaActualizar.getPaisOrigen());
                return;
            }

            // 2do clic: aplicar los cambios al nodo
            Marca marcaNueva = new Marca();
            marcaNueva.setIdMarca(marcaActualizar.getIdMarca());
            marcaNueva.setNombreMarca(txtNombre.getText().trim());
            marcaNueva.setDescripcion(txtDescripcion.getText().trim());
            marcaNueva.setPaisOrigen(txtPaisOrigen.getText().trim());
            marcaNueva.setEstado(marcaActualizar.isEstado());
            marcaNueva.setFechaCreacion(marcaActualizar.getFechaCreacion());
            marcaNueva.setFechaModificacion(marcaActualizar.getFechaModificacion());

            marControl.actualizarNodo(marcaNueva);   // BD + nodo de la lista

            Mensajes.exito("La marca ha sido actualizada exitosamente!");
            limpiarCampos();
            mostrarNodo(nodoActual);   // refresca el panel de la derecha
        } catch (Exception e) {
            Mensajes.error(e.getMessage());
        }
    }//GEN-LAST:event_btnACTUALIZARActionPerformed

